import './shim.mjs';
import assert from 'node:assert/strict';
const base = process.argv[2] + '/js/';
const flush = async () => { for (let i = 0; i < 8; i++) await Promise.resolve() };
let timers = [];
globalThis.setTimeout = (fn) => { timers.push(fn); return fn };
globalThis.clearTimeout = (fn) => { timers = timers.filter((t) => t !== fn) };
window.requestAnimationFrame = () => 0;
const pending = [];
globalThis.fetch = (url) => new Promise((resolve) => pending.push({ url, resolve }));
const store = await import(base + 'store.js');
const log = await import(base + 'panels/log.js');
const panel = log.build().el;
const reply = async (data) => {
  assert.equal(pending.length, 1);
  pending.shift().resolve({ json: async () => ({ status: 'idle', ...data }) });
  await flush();
};
const tick = () => { assert.equal(timers.length, 1); timers.shift()() };
store.startPolling(1);
await flush();
assert.equal(pending.length, 1);
assert.equal(timers.length, 0, 'slow fetch must not schedule overlapping status requests');
await reply({ since: 13, events: [{ i: 12, t: 'sys', text: 'loaded 515' }] });
assert.equal(panel.children.length, 1);
tick();
assert.equal(pending[0].url, '/status?since=13');
await reply({ since: 14, events: [{ i: 12, t: 'sys', text: 'loaded 515' }, { i: 13, t: 'sys', text: 'next' }] });
assert.equal(panel.children.length, 2, 'replayed event must not append twice');
tick();
store.resetSince();
await reply({ since: 15, events: [{ i: 14, t: 'sys', text: 'stale before clear' }] });
assert.equal(panel.children.length, 2, 'clear invalidates a pending response');
tick();
assert.equal(pending[0].url, '/status?since=0');
await reply({ since: 16, reset_log: true, events: [{ i: 15, t: 'sys', text: 'after clear' }] });
assert.equal(panel.children.length, 1);
tick();
await reply({ since: 2, events: [{ i: 1, t: 'sys', text: 'restarted backend' }] });
assert.equal(panel.children.length, 1, 'new backend generation clears prior log');
assert.equal(store.S.reset_log, true);
console.log('status ok: serialized polling, event dedup, clear and backend restart');
