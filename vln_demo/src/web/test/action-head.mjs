import './shim.mjs';
import assert from 'node:assert/strict';

const base = process.argv[2] + '/js/';
const calls = [];
const ROOT = '/data/zerovln/artifacts';
const A = ROOT + '/experiment/global_step_001000';
let fail = false;
globalThis.fetch = async (url) => {
  calls.push(url);
  if (url.startsWith('/cmd')) return { text: async () => fail ? '加载被拒绝' : 'ok' };
  if (url.startsWith('/action-head/catalog')) return { json: async () => ({ ok: true,
    checkpoints: [
      { path: A, group: 'experiment', experiment: 'bootstrap experiment', step: 1000, version: 'v4.3' },
      { path: A + '-old', group: 'experiment', experiment: 'bootstrap experiment', step: 500, version: 'v4.3' },
      { path: ROOT + '/other', group: 'other', experiment: 'd012 other', step: 2000, version: 'v3' },
    ], rejected: [], warnings: [] }) };
  const path = new URL(url, 'http://test').searchParams.get('path') || ROOT;
  const checkpoint = path === A ? { path: A, version: 'v4.3' } : null;
  return { json: async () => ({ ok: true, path, root: ROOT, parent: checkpoint ? ROOT : null,
    checkpoint, directories: checkpoint ? [] : [{ name: 'snapshot', path: A }] }) };
};
const { checkpointPicker } = await import(base + 'action-head.js');
const { S } = await import(base + 'store.js');
S.locked = false;
const picker = checkpointPicker();
document.body.appendChild(picker.root);
const g = (id) => document.getElementById(id);
const tick = () => new Promise((r) => setTimeout(r, 10));
assert.equal(calls.length, 0, 'building controls must not load or browse');
picker.show(true);
await tick();
assert(calls[0].startsWith('/action-head/catalog'), 'show automatically discovers snapshots');
assert(g('ah-choices').hidden);
assert(g('ah-load').disabled);
g('ah-confirm').fire('click');
assert(!g('ah-choices').hidden);
assert(g('ah-picker-controls').hidden);
assert(!g('ah-picked').hidden);
assert(g('ah-picked-label').textContent.includes('bootstrap experiment'));
assert.equal(g('ah-step').options.length, 3);
assert.equal(g('ah-step').value, '', 'listing must not select the newest checkpoint');
assert(g('ah-load').disabled);
assert.equal(calls.filter(u => u.startsWith('/cmd')).length, 0);
g('ah-step').value = A + '-old';
g('ah-step').fire('change');
assert.equal(g('ah-path').value, A + '-old');
assert(g('ah-choices').hidden);
assert(!g('ah-chosen').hidden);
assert(g('ah-chosen-label').textContent.includes('step 500'));
g('ah-change-step').fire('click');
assert(!g('ah-choices').hidden);
assert(g('ah-chosen').hidden);
g('ah-step').value = A + '-old';
g('ah-step').fire('change');
assert(g('ah-selection').textContent.includes('harness v4.3'));
g('ah-change').fire('click');
assert(!g('ah-picker-controls').hidden);
assert(g('ah-picked').hidden);
assert(g('ah-choices').hidden);
g('ah-search').value = 'd012';
g('ah-search').fire('input');
assert(g('ah-load').disabled);
assert(g('ah-choices').hidden);
g('ah-search').value = 'missing';
g('ah-search').fire('input');
assert(g('ah-confirm').disabled);
g('ah-search').value = 'bootstrap';
g('ah-search').fire('input');
g('ah-refresh').fire('click');
await tick();
assert(calls.includes('/action-head/catalog?refresh=1'));
assert(g('ah-load').disabled);
g('ah-confirm').fire('click');
g('ah-step').value = A;
g('ah-step').fire('change');
assert.equal(g('ah-path').value, A);
assert(!g('ah-load').disabled);
assert.equal(calls.filter((u) => u.startsWith('/cmd')).length, 0, 'listing must only stage');
g('ah-path').value = A + '/action_head';
g('ah-path').fire('input');
assert(g('ah-load').disabled, 'editing the path must invalidate the inspected selection');
g('ah-path').value = A;
g('ah-browse').fire('click');
await tick();
g('ah-load').fire('click');
await tick();
assert.equal(calls.filter((u) => u.startsWith('/cmd')).length, 1);
const load = new URL(calls.at(-1), 'http://test');
assert.equal(load.searchParams.get('do'), 'load_action_head');
assert.equal(load.searchParams.get('path'), A);
assert.equal(load.searchParams.has('model'), false);
picker.sync({ status: 'idle', action_head: { state: 'loading', active: { path: 'old' }, pending: { path: A } } });
assert(g('ah-load').disabled);
assert(g('ah-active').textContent.includes('old'));
assert(g('ah-loading').title.includes(A));
picker.sync({ status: 'idle', action_head: { state: 'error', active: { path: 'old' }, error: 'OOM' } });
assert(g('ah-error').textContent.includes('OOM'));
assert(g('ah-active').textContent.includes('old'));
assert(!g('ah-load').disabled);
fail = true;
g('ah-load').fire('click');
await tick();
assert(g('ah-error').textContent.includes('加载被拒绝'));
picker.sync({ status: 'running', action_head: { state: 'loaded', active: { path: A } } });
assert(g('ah-load').disabled);
assert.equal(g('ah-path').value, A, 'status must not overwrite the staged directory');
console.log('manual selection, confirmation, independent request, error and running states passed');
